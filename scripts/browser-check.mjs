import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

await mkdir('qa', { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE || undefined });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:3000', { waitUntil: 'networkidle' });
await page.waitForFunction(() => getComputedStyle(document.querySelector('.hero-word')).opacity === '1');
await page.waitForTimeout(1000);
await page.screenshot({ path: 'qa/desktop.png' });
assert.match(await page.title(), /Wrapped 2026/);
assert.equal(await page.locator('.history-card').count(), 8);
await page.getByRole('button', { name: /Night owl/ }).click();
await page.getByRole('heading', { name: 'THE NIGHT OWL' }).waitFor();
assert.equal(await page.getByRole('button', { name: /Night owl/ }).getAttribute('aria-pressed'), 'true');
const downloadEvent = page.waitForEvent('download');
await page.getByRole('button', { name: 'SAVE YOUR VIBE CARD' }).click();
const download = await downloadEvent;
assert.equal(download.suggestedFilename(), 'wrapped-2026-Night-owl.png');
await download.saveAs('qa/night-owl.png');
for (const name of ['Nostalgic one', 'Party starter', 'Dreamer', 'Main character']) {
  await page.getByRole('button', { name: new RegExp(name, 'i') }).click();
  await page.waitForTimeout(600);
  assert.equal(await page.getByRole('button', { name: new RegExp(name, 'i') }).getAttribute('aria-pressed'), 'true');
}
assert.equal(await page.getByRole('button', { name: /BUY TOKEN/ }).isDisabled(), true);
assert.equal(await page.getByRole('button', { name: /VIEW ON DEXSCREENER/ }).isDisabled(), true);
await page.getByRole('button', { name: 'Pause animations' }).click();
assert.equal(await page.locator('.site').evaluate(el => el.classList.contains('motion-paused')), true);
await page.setViewportSize({ width: 390, height: 844 });
await page.goto('http://127.0.0.1:3000', { waitUntil: 'networkidle' });
await page.waitForFunction(() => getComputedStyle(document.querySelector('.hero-word')).opacity === '1');
await page.waitForTimeout(1000);
await page.screenshot({ path: 'qa/mobile.png' });
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
await page.getByRole('button', { name: 'Open menu' }).click();
await page.getByRole('link', { name: 'Find your vibe', exact: true }).click();
assert.equal(await page.getByRole('button', { name: 'Open menu' }).getAttribute('aria-expanded'), 'false');
await page.emulateMedia({ reducedMotion: 'reduce' });
await page.reload({ waitUntil: 'networkidle' });
assert.equal(await page.locator('.hero-record').evaluate(el => getComputedStyle(el).animationName), 'none');
await page.getByRole('button', { name: /Dreamer/ }).click();
await page.getByRole('heading', { name: 'THE DREAMER' }).waitFor();
await page.screenshot({ path: 'qa/mobile-vibe.png' });
assert.deepEqual(errors, []);
console.log('PASS: desktop/mobile rendering, 8 milestones, 5 personalities, PNG download, disabled token links, pause control, mobile navigation, reduced motion, no page errors or mobile overflow.');
await browser.close();
